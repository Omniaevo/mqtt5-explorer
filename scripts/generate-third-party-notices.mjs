/**
 * Scan the licenses of every package shipped inside the app and write
 * THIRD-PARTY-NOTICES.txt. Exit with code 1 when a license is not allowed.
 *
 * Usage: npm run licenses
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_FILE = path.join(ROOT, "THIRD-PARTY-NOTICES.txt");

// Dev dependencies that Vite bundles into the renderer, so they ship in the app.
const BUNDLED_DEV_DEPENDENCIES = [
  "@fluentui/svg-icons",
  "pinia",
  "reka-ui",
  "vue",
  "vue-router",
];

// Shipped assets that are not npm packages. The license text lives in the repo.
const EXTRA_NOTICES = [
  {
    name: "Selawik",
    license: "OFL-1.1",
    repository: "https://github.com/microsoft/Selawik",
    textFile: "src/renderer/src/assets/fonts/selawik/OFL.txt",
  },
];

// SPDX ids that are compatible with GPL-3.0-only.
const ALLOWED_LICENSES = new Set([
  "0BSD",
  "Apache-2.0",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "BlueOak-1.0.0",
  "CC0-1.0",
  "ISC",
  "MIT",
  "MIT-0",
  "Python-2.0",
  "Unlicense",
]);

const LICENSE_FILE_PATTERN = /^(licen[cs]e|copying)([.-].+)?$/i;
const SEPARATOR = "=".repeat(78);

function readManifest(packageDir) {
  return JSON.parse(
    readFileSync(path.join(packageDir, "package.json"), "utf8")
  );
}

/** Find a package directory the way Node does: walk up the node_modules chain. */
function resolvePackageDir(name, fromDir) {
  for (let dir = fromDir; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, "node_modules", name);
    if (existsSync(path.join(candidate, "package.json"))) return candidate;
    if (dir === path.dirname(dir)) return null;
  }
}

/** Collect root packages and their runtime dependencies (peer deps are skipped). */
function collectShippedPackages(rootNames) {
  const found = new Map();
  const queue = rootNames.map((name) => ({ name, fromDir: ROOT }));

  while (queue.length > 0) {
    const { name, fromDir } = queue.pop();
    const packageDir = resolvePackageDir(name, fromDir);
    if (packageDir === null || found.has(packageDir)) continue;

    const manifest = readManifest(packageDir);
    found.set(packageDir, manifest);

    const children = {
      ...manifest.dependencies,
      ...manifest.optionalDependencies,
    };
    for (const childName of Object.keys(children)) {
      queue.push({ name: childName, fromDir: packageDir });
    }
  }
  return found;
}

function readLicenseId(manifest) {
  const license = manifest.license ?? manifest.licenses;
  if (typeof license === "string") return license;
  if (license?.type) return license.type;
  if (Array.isArray(license)) return license.map((l) => l.type).join(" OR ");
  return "UNKNOWN";
}

/** Accept "(MIT OR Apache-2.0)" style expressions when every term is allowed. */
function isAllowed(licenseId) {
  const terms = licenseId.split(/[\s()]+|\bOR\b|\bAND\b/).filter(Boolean);
  return terms.length > 0 && terms.every((term) => ALLOWED_LICENSES.has(term));
}

/** Join every license file of the package (dual-licensed ones have several). */
function readLicenseText(packageDir) {
  const texts = readdirSync(packageDir)
    .filter((entry) => LICENSE_FILE_PATTERN.test(entry))
    .map((entry) => readFileSync(path.join(packageDir, entry), "utf8").trim());
  return texts.length > 0 ? texts.join("\n\n---\n\n") : null;
}

function describePackage(packageDir, manifest) {
  const repository = manifest.repository?.url ?? manifest.repository ?? "";
  return {
    name: manifest.name,
    version: manifest.version,
    license: readLicenseId(manifest),
    repository: String(repository).replace(/^git\+/, ""),
    author: manifest.author?.name ?? manifest.author ?? "",
    text: readLicenseText(packageDir),
  };
}

function formatMissingLicenseText(pkg) {
  const author = pkg.author ? ` Author: ${pkg.author}.` : "";
  return `(The package has no license file. Declared license: ${pkg.license}.${author})`;
}

function readExtraNotice({ textFile, ...notice }) {
  const text = readFileSync(path.join(ROOT, textFile), "utf8").trim();
  return { author: "", ...notice, text };
}

function formatEntry(pkg) {
  const lines = [
    SEPARATOR,
    pkg.version ? `${pkg.name}@${pkg.version}` : pkg.name,
    `License: ${pkg.license}`,
  ];
  if (pkg.repository) lines.push(`Source: ${pkg.repository}`);
  lines.push("", pkg.text ?? formatMissingLicenseText(pkg), "");
  return lines.join("\n");
}

function formatNotices(packages) {
  const header = [
    "THIRD-PARTY NOTICES",
    "",
    "MQTT5 Explorer includes the third-party software listed below.",
    "Electron and Chromium notices ship with the app (LICENSE and LICENSES.chromium.html).",
    "Generated by scripts/generate-third-party-notices.mjs. Do not edit by hand.",
    "",
  ];
  return [...header, ...packages.map(formatEntry)].join("\n");
}

function main() {
  const manifest = readManifest(ROOT);
  const rootNames = [
    ...Object.keys(manifest.dependencies),
    ...BUNDLED_DEV_DEPENDENCIES,
  ];

  const packages = [...collectShippedPackages(rootNames)]
    .map(([packageDir, packageManifest]) =>
      describePackage(packageDir, packageManifest)
    )
    .sort(
      (a, b) =>
        a.name.localeCompare(b.name) || a.version.localeCompare(b.version)
    );
  const extras = EXTRA_NOTICES.map(readExtraNotice);

  const rejected = packages.filter((pkg) => !isAllowed(pkg.license));
  const withoutText = packages.filter((pkg) => pkg.text === null);

  writeFileSync(OUTPUT_FILE, formatNotices([...packages, ...extras]));
  console.log(
    `${packages.length} packages scanned, ${extras.length} extra notices, notices written to ${OUTPUT_FILE}`
  );

  for (const pkg of withoutText) {
    console.warn(
      `No license file: ${pkg.name}@${pkg.version} (${pkg.license})`
    );
  }
  for (const pkg of rejected) {
    console.error(
      `License not allowed: ${pkg.name}@${pkg.version} (${pkg.license})`
    );
  }
  if (rejected.length > 0) process.exit(1);
}

main();
